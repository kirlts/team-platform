// Capability «API documentada y cliente» (docs/CAPACIDADES-1.0.md): every route has a schema, the API publishes a valid OpenAPI 3.1 and the client package is
// generated from it. From an instance that is running: its contract is read over HTTP, validated, turned into the types of the client (openapi-typescript), the
// client is compiled against those types (a route or a field that the contract does not have stops the compilation) and, built that way, it signs in as two people,
// sends, replies and reads the thread. (That the files committed in packages/client are those of the contract is the case of src/client-contract.test.js.) Needs the dependencies of the client package: `npm ci --prefix packages/client`.
import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { after, before, test } from 'node:test'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { validate } from '@readme/openapi-parser'
import { routePolicies } from '../../src/identity/index.js'
import { addMember, makeEnv, TEST_PASSWORD, until } from '../../src/testing/helpers.js'
import { requestErrorCodes, serializeErrorCodes } from '../../packages/client/scripts/contract.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const CLIENT = path.join(ROOT, 'packages/client')
const METHODS = ['get', 'put', 'post', 'delete', 'patch']

let env
let baseUrl
let work
before(async () => {
  env = await makeEnv({ worker: true, autoPublish: true, config: { identity: { login: { ipMax: 1000 } } } })
  await addMember(env, { email: 'ana@x.org', name: 'Ana' })
  await addMember(env, { email: 'beto@x.org', name: 'Beto' })
  await env.app.listen({ host: '127.0.0.1', port: 0 })
  baseUrl = `http://127.0.0.1:${env.app.server.address().port}`
  work = mkdtempSync(path.join(process.env.TMPDIR ?? tmpdir(), 'e2e-cliente-'))
})
after(async () => {
  await env.close()
  rmSync(work, { recursive: true, force: true })
})

/** `fetch` that keeps the cookies of the server, as a browser does for one origin. */
function jarFetch () {
  const jar = new Map()
  return async (input, init = {}) => {
    const headers = new Headers(init.headers)
    if (jar.size) headers.set('cookie', [...jar].map(([k, v]) => `${k}=${v}`).join('; '))
    const res = await fetch(input, { ...init, headers })
    for (const line of res.headers.getSetCookie()) {
      const [pair] = line.split(';')
      const eq = pair.indexOf('=')
      if (pair.slice(eq + 1)) jar.set(pair.slice(0, eq), pair.slice(eq + 1))
      else jar.delete(pair.slice(0, eq))
    }
    return res
  }
}

test('the running instance publishes a valid OpenAPI 3.1 that names every route it has; the client generated from it compiles and sends and replies', async () => {
  // The contract, over HTTP, as any outside system reads it.
  const res = await fetch(`${baseUrl}/api/openapi.json`)
  assert.equal(res.status, 200)
  const doc = await res.json()
  assert.match(doc.openapi, /^3\.1\./)
  const valid = await validate(structuredClone(doc))
  assert.equal(valid.valid, true, JSON.stringify(valid.errors ?? valid).slice(0, 500))
  const documented = new Set(Object.entries(doc.paths).flatMap(([p, item]) => METHODS.filter((m) => item[m]).map((m) => `${m.toUpperCase()} ${p.replace(/^\/api/, '')}`)))
  const routes = routePolicies.get(env.app).filter((r) => METHODS.includes(r.method.toLowerCase())).map((r) => `${r.method} ${r.url.replace(/^\/api/, '')}`)
  // The contract does not list itself.
  const undocumented = routes.filter((r) => r !== 'GET /openapi.json' && !documented.has(r.replace(/:(\w+)/g, '{$1}')))
  assert.deepEqual(undocumented, [], 'a route of the server is not in its contract')

  // The client, generated from that contract: types from the contract of the running instance, the rest of the package as it is.
  const { default: openapiTS, astToString } = await import(pathToFileURL(path.join(CLIENT, 'node_modules/openapi-typescript/dist/index.mjs')).href)
  const types = '// Generated by `npm run gen:client` from openapi.json (openapi-typescript). Do not edit.\n' + astToString(await openapiTS(doc))
  const pkg = path.join(work, 'client')
  mkdirSync(pkg, { recursive: true })
  cpSync(path.join(CLIENT, 'src'), path.join(pkg, 'src'), { recursive: true, filter: (from) => !from.includes(`${path.sep}src${path.sep}react`) && !from.endsWith('.test.ts') })
  writeFileSync(path.join(pkg, 'src/generated/schema.ts'), types)
  writeFileSync(path.join(pkg, 'src/generated/error-codes.ts'), serializeErrorCodes(requestErrorCodes()))
  writeFileSync(path.join(pkg, 'package.json'), '{ "type": "module" }')
  writeFileSync(path.join(pkg, 'tsconfig.json'), JSON.stringify({
    extends: path.join(CLIENT, 'tsconfig.json'),
    compilerOptions: { noEmit: false, outDir: 'dist', rootDir: 'src', types: [], declaration: false, typeRoots: [] },
    include: ['src']
  }))
  execFileSync(process.execPath, [path.join(CLIENT, 'node_modules/typescript/bin/tsc'), '-p', path.join(pkg, 'tsconfig.json')], { cwd: pkg, stdio: ['ignore', 'pipe', 'pipe'] }) // a type error throws with the compiler's output

  // The client, as built, in the hands of two people.
  const { createTeamClient, isTeamApiError } = await import(pathToFileURL(path.join(pkg, 'dist/index.js')).href)
  const asPerson = async (email) => {
    const team = createTeamClient({ baseUrl, fetch: jarFetch(), requestMarker: 'panel' })
    await team.auth.login({ email, password: TEST_PASSWORD })
    return team
  }
  const anon = createTeamClient({ baseUrl, fetch: jarFetch(), requestMarker: 'panel' })
  await assert.rejects(anon.me.get(), (err) => isTeamApiError(err) && err.status === 401 && err.code === 'unauthenticated')
  const ana = await asPerson('ana@x.org')
  assert.equal((await ana.me.get()).email, 'ana@x.org')
  const created = await ana.inputs.create({ text: 'la exportación a PDF sale cortada', files: [], links: [] })
  const input = await until(async () => {
    const v = await ana.inputs.get(created.input_id)
    if (v.status === 'failed') throw new Error('the analysis failed')
    return v.status === 'published' ? v : null
  }, { timeoutMs: 15000 })
  const messageId = String(input.message_ids[0])
  const beto = await asPerson('beto@x.org')
  const replied = await beto.replies.create(messageId, { body: 'Lo veo en la versión 2.', kind: 'answer' })
  assert.equal(replied.status, 'answered')
  const thread = await ana.messages.get(messageId)
  assert.equal(thread.id, messageId)
  assert.deepEqual(thread.replies.map((r) => r.body), ['Lo veo en la versión 2.'])
  assert.equal((await ana.messages.list({ query: { filters: [], q: '' }, meId: String((await ana.me.get()).id) })).some((m) => m.id === messageId), true)
  // The error of the contract arrives typed: the author cannot reply to her own message.
  await assert.rejects(ana.replies.create(messageId, { body: 'yo mismo', kind: 'answer' }), (err) => isTeamApiError(err) && err.status === 403 && err.code === 'author_cannot_reply')
})
