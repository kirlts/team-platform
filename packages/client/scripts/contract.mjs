// The two things of the server that the client copies as files: the OpenAPI contract and the list of request error
// codes. Both are read from the code that runs (the application built in process, the sources scanned), never typed by hand.
// `scripts/gen.mjs` writes them; `src/client-contract.test.js` fails when the written copy and the live one differ.
import { readdirSync, readFileSync, statSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('../../..', import.meta.url))
const SRC = join(ROOT, 'src')

/** The contract exactly as `GET /api/openapi.json` serves it, from an application built in process with the test configuration. */
export async function liveOpenapi () {
  const { makeEnv } = await import('../../../src/testing/helpers.js')
  const env = await makeEnv()
  try {
    const res = await env.app.inject({ method: 'GET', url: '/api/openapi.json' })
    if (res.statusCode !== 200) throw new Error(`GET /api/openapi.json answered ${res.statusCode}`)
    return JSON.parse(res.body)
  } finally {
    await env.close()
  }
}

export const serializeContract = (doc) => `${JSON.stringify(doc, null, 2)}\n`

function sources (dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name)
    if (statSync(path).isDirectory()) return name === 'testing' || name === 'test' ? [] : sources(path)
    return name.endsWith('.js') && !name.endsWith('.test.js') && !name.endsWith('.bench.mjs') ? [path] : []
  })
}

/** The codes a request can fail with, sorted: the same scan `src/error-codes.test.js` runs to demand a translation for each. */
export function requestErrorCodes () {
  const text = sources(SRC).map((p) => readFileSync(p, 'utf8')).join('\n')
  const grab = (re) => [...text.matchAll(re)].map((m) => m[1])
  const codes = new Set([
    ...grab(/\b(?:badRequest|forbidden|conflict|unprocessable)\((?:[^()]|\([^()]*\))*?,\s*'([a-z_]+)'/g),
    ...grab(/\bemptyCode: '([a-z_]+)'/g),
    ...grab(/\.send\(\{ code: '([a-z_]+)'/g),
    // The default code of each helper of src/domain/errors.js: `forbidden(message)` answers `forbidden`, and so on.
    ...grab(/new AppError\(\d+,\s*'([a-z_]+)'/g),
    ...grab(/\bcode = '([a-z_]+)'(?:, extra)?\) =>/g)
  ])
  return [...codes].sort()
}

export function serializeErrorCodes (codes) {
  return `// Generated by \`npm run gen:client\` from the sources of the server. Do not edit.
/** Every \`code\` the API can answer a request with (\`{ code, message }\`), besides the generic ones of the HTTP status. */
export const REQUEST_ERROR_CODES = [
${codes.map((c) => `  '${c}',`).join('\n')}
] as const

export type RequestErrorCode = (typeof REQUEST_ERROR_CODES)[number]
`
}
