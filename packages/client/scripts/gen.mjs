// `npm run gen:client`: rewrites the three files the client takes from the server.
//   openapi.json                 the live contract (GET /api/openapi.json of an application built in process)
//   src/generated/schema.ts    its types, by openapi-typescript
//   src/generated/error-codes.ts the codes of request errors, scanned from the server's sources
// With `--check` it writes nothing and exits 1 if any of the three differs from what the server says now.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'
import { liveOpenapi, requestErrorCodes, serializeContract, serializeErrorCodes } from './contract.mjs'

const here = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url))
const HEADER = '// Generated by `npm run gen:client` from openapi.json (openapi-typescript). Do not edit.\n'

export async function schemaTypes (doc) {
  const ast = await openapiTS(doc)
  return HEADER + astToString(ast)
}

const check = process.argv.includes('--check')
const contract = serializeContract(await liveOpenapi())
const files = {
  'openapi.json': contract,
  'src/generated/schema.ts': await schemaTypes(JSON.parse(contract)),
  'src/generated/error-codes.ts': serializeErrorCodes(requestErrorCodes())
}
let stale = 0
for (const [path, text] of Object.entries(files)) {
  let current = null
  try { current = readFileSync(here(path), 'utf8') } catch { /* not generated yet */ }
  if (current === text) continue
  stale += 1
  if (check) console.error(`${path} differs from the server`)
  else { writeFileSync(here(path), text); console.log(`wrote ${path}`) }
}
if (check && stale) process.exit(1)
if (!stale) console.log('client files are up to date')
